SCRIPT_PATH = r"C:\Users\PANDA\Desktop\Updated.py"
ICO_PATH    = r"C:\Users\PANDA\Desktop\panda.ico"
DLL_PATH    = r"C:\Users\PANDA\Desktop\sppc64.dll"
APP_NAME = "Panda Tool"   # name of the final exe (no extension)
# =====================================================

# =====================================================
# CHANGE THIS TO WHATEVER FOLDER NAME YOU WANT
# DLL will extract to: C:\Users\PANDA\AppData\Local\Temp\MyAppFiles\
# =====================================================
TEMP_FOLDER_NAME = "MyAppFiles"
# =====================================================

MERGED_FILE = "_merged_app.py"


def ensure_pyinstaller():
    try:
        import PyInstaller  # noqa
    except ImportError:
        print("Installing PyInstaller...")
        subprocess.check_call([sys.executable, "-m", "pip", "install", "pyinstaller"])


def file_to_b64(path):
    with open(path, "rb") as f:
        return base64.b64encode(f.read()).decode()


def build_merged_script(original_code, dll_b64, dll_filename):
    header = f'''"""
Auto-generated by build.py
"""

import base64
import ctypes
import os
import sys

_DLL_B64 = """
{dll_b64}
"""

_DLL_FILENAME = "{dll_filename}"

TEMP_FOLDER_NAME = "{TEMP_FOLDER_NAME}"


def _extract_dll():
    # Always extracts to: C:\\Users\\PANDA\\AppData\\Local\\Temp\\MyAppFiles\\
    temp_dir = os.path.join(os.environ.get("TEMP", os.getcwd()), TEMP_FOLDER_NAME)

    # Create the folder if it does not exist
    os.makedirs(temp_dir, exist_ok=True)

    output_path = os.path.join(temp_dir, _DLL_FILENAME)

    # Only extract if not already there — skips re-extracting on every launch
    if not os.path.exists(output_path):
        data = base64.b64decode(_DLL_B64.strip())
        with open(output_path, "wb") as f:
            f.write(data)

    return output_path


# Extract DLL silently before your script runs
DLL_PATH = _extract_dll()

# ======================= YOUR ORIGINAL SCRIPT BELOW =======================

'''
    return header + original_code


def build_exe():
    cmd = [
        sys.executable, "-m", "PyInstaller",
        "--onefile",
        "--noconsole",
        "--uac-admin",
        "--icon", ICO_PATH,
        "--name", APP_NAME,
        MERGED_FILE,
    ]
    print("Running:", " ".join(cmd))
    subprocess.check_call(cmd)


def main():
    for label, path in [("Script", SCRIPT_PATH), ("ICO", ICO_PATH), ("DLL", DLL_PATH)]:
        if not os.path.isfile(path):
            sys.exit(f"{label} file not found: {path}")

    ensure_pyinstaller()

    print("Reading your original script...")
    with open(SCRIPT_PATH, "r", encoding="utf-8") as f:
        original_code = f.read()

    print("Encoding DLL...")
    dll_b64 = file_to_b64(DLL_PATH)
    dll_filename = os.path.basename(DLL_PATH)

    print("Merging DLL-embedding code with your script...")
    merged_code = build_merged_script(original_code, dll_b64, dll_filename)
    with open(MERGED_FILE, "w", encoding="utf-8") as f:
        f.write(merged_code)

    print("Building exe...")
    build_exe()

    exe_path = os.path.join("dist", f"{APP_NAME}.exe")
    print(f"\nDone! Your exe is at: {exe_path}")


if __name__ == "__main__":
    main()